"""Generate original, deterministic table effects; no third-party samples."""
import math,random,wave,struct
from pathlib import Path
out=Path(__file__).resolve().parents[1]/'dist/assets/audio';out.mkdir(exist_ok=True)
rate=44100
for name,duration in [('move',.16),('deal',.15),('chips',.28),('hit',.4),('miss',.4),('turn',.22),('win',.8)]:
 rng=random.Random(name);samples=[];low=0
 for i in range(int(rate*duration)):
  t=i/rate;noise=rng.uniform(-1,1);low=.85*low+.15*noise
  if name=='move':v=(.6*math.sin(2*math.pi*340*t)+noise*.3)*math.exp(-35*t)
  elif name=='deal':v=(noise-low)*math.sin(math.pi*t/duration)**2*.4
  elif name=='chips':
   v=0
   for at in [0,.045,.11]:
    q=t-at
    if q>=0:v+=(math.sin(2*math.pi*1800*q)+.5*math.sin(2*math.pi*2700*q))*math.exp(-55*q)*.3
  elif name=='hit':v=(low+math.sin(2*math.pi*(100*t-60*t*t))*.25)*math.exp(-12*t)
  elif name=='miss':v=low*math.sin(math.pi*t/duration)**2
  elif name=='turn':v=math.sin(2*math.pi*660*t)*math.sin(math.pi*t/duration)**2*.22
  else:
   f=[523.25,659.25,783.99][min(2,int(t/.22))];v=math.sin(2*math.pi*f*t)*math.sin(math.pi*(t%.22)/.22)**2*.22*min(1,(duration-t)*10)
  samples.append(max(-.85,min(.85,v*.65)))
 with wave.open(str(out/(name+'.wav')),'wb') as w:
  w.setparams((1,2,rate,0,'NONE','not compressed'));w.writeframes(b''.join(struct.pack('<h',round(v*32767)) for v in samples))
(out/'README.txt').write_text('Original synthesized Imperial table effects, generated by scripts/build-audio.py. 44.1 kHz mono PCM WAV. No third-party samples. These cues are integrated into the browser game table; Sound control enables or mutes them. Unity Asset Store packs are not redistributed in this folder.\n')
